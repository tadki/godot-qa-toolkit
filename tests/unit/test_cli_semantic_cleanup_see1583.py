"""SEE-1583 §SPEC-002 — 内部语义与命名清理判据。

判据面：
- 模块面：`accept/` → `gherkin/`、`canonical/` → `measurement/`，旧目录不存在；
- handler / argparse dest：无 cmd_gherkin/cmd_canonical 等旧 handler，新 handler
  齐备；gherkin_command / measure_command dest 生效；
- machine 面：src 内所有 stdout `tool` 字面值 ∈ 新命名集合；三个版本化标识
  `measurement-suite/3` / `measurement-report/3` / `test-attribution/5` 生效，
  旧 schema 串零残留（无双读）；
- 旧语义文案：SEE-1581 定稿后，mutation 侧不得再写「自动回退全脸」类
  help/docstring（fail-loud + 文件级有界回退是现行语义）；
- 生成产物头：`generated by gqt gherkin compile`，旧 `gqt accept compile` 零残留。
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "src" / "godot_qa_toolkit"

ALLOWED_TOOLS = {
    "gherkin", "mutation",
    "measure.suite", "measure.run", "measure.diagnose", "measure.map-update",
    "measure.coverage", "measure.complexity", "measure.arch", "measure.parity",
    "measure.registry-diff", "measure.risk",
}

TOOL_LITERAL = re.compile(r'"tool":\s*"([^"]+)"')

OLD_TOOL_LITERALS = ("accept", "arch", "canonical", "canonical-diagnose",
                     "complexity", "coverage", "parity", "recipe", "registry",
                     "risk")

OLD_SCHEMA_PREFIXES = ("canonical-recipe/", "canonical-report/",
                       "canonical-test-attribution/")

# mutation 侧旧「自动回退全脸」文案特征（现行语义：fail-loud / 有界文件级
# 回退 / zero-ref 终态 / 全脸仅显式审计）。measurement/increment 的「回退全脸」
# 是映射重建的校准策略，不属此判据，故仅扫 mutation/。
# 覆盖三类表述：旧回退动词（退回/走/回退/使用/退化为 + 全脸）、隐式继续
# （按全脸继续/全脸继续）、缺省面失实（全脸默认/缺省全脸/`= **全脸**`/
# defaults to the full face/uses the full face）。合法表述（「全脸仅
# 显式审计」「显式全脸面/基线」「取消自动全脸」）不含上述组合，不会被误伤。
STALE_FULL_FACE = re.compile(
    r"退回全脸|走全脸|回退全脸|全脸回退|"
    r"按全脸继续|全脸继续|全脸默认|=\s*\*\*全脸\*\*|"
    r"使用全脸|退化为全脸|缺省全脸|"
    r"falls back to the full face|falls back to full suite|"
    r"defaults to the full face|uses the full face")


def _py_texts(root: Path) -> list[tuple[Path, str]]:
    return [(p, p.read_text(encoding="utf-8")) for p in sorted(root.rglob("*.py"))]


