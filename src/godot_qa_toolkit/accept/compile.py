IR_DIR = "acceptance/ir"
GENERATED_DIR = "acceptance/generated"

# 中文/非 ASCII 场景名 → GUT 合法测试函数名后缀的标识符化：非 [A-Za-z0-9_]
# 全部映射为 _ + 码点序号（同 Feature 内 scenario 名唯一性由序号保障——
# 归因不串：manifest 按 sha 级键对回原 scenario）。
_IDENT_SAFE = re.compile(r"[^A-Za-z0-9_]")


def _ident(name: str, index: int) -> str:
    slug = _IDENT_SAFE.sub(lambda m: f"_{ord(m.group(0)) & 0xFF:02x}", name)
    slug = re.sub(r"_+", "_", slug).strip("_")
    if not slug:
        slug = "scenario"
    return f"test_{slug}_{index:03d}"


def sha256_of(data: bytes | str) -> str:
    if isinstance(data, str):
        data = data.encode("utf-8")
    return hashlib.sha256(data).hexdigest()


@dataclass(frozen=True)
class CompiledSuite:
    feature_key: str
    ir: dict
    ir_json: str
    generated_gd: str
    worker_gd: str
    manifest: dict


def _scenario_ir(scenario: Scenario, index: int,
                 expansions: list) -> list[dict]:
    """一个 parser Scenario → 若干 IR case（Outline 每行一个 case）。"""
    cases = []
    for row_line, values, steps, types in expansions:
        cases.append({
            "scenario": scenario.name,
            "scenario_line": scenario.line,
            "example_row_line": row_line,
            "values": values,
            "steps": [{"keyword": s.keyword, "text": s.text, "line": s.line}
                      for s in steps],
            "types": dict(types),
            "then_unchanged": list(scenario.unchanged),
            "mutation_exempt": scenario.mutation_exempt,
            "test_name": f"{_ident(scenario.name, index)}_{len(cases):02d}",
        })
    return cases


def build_ir(feature_text: str, feature_path: str) -> dict:
    """parse + schema 校验后产出版本化 IR dict（零写入，纯数据面）。"""
    feature = parse(feature_text, path=feature_path)
    cases: list[dict] = []
    for idx, scenario in enumerate(feature.scenarios):
        cases.extend(_scenario_ir(scenario, idx, scenario.expansions()))
    ir = {
        "ops_version": OPS_VERSION,
        "feature": feature.name,
        "source_path": str(feature_path),
        "cases": cases,
    }
    return ir


def _generated_gd_source(ir: dict, ir_path_res: str) -> str:
    """数据驱动 GUT 测试：运行时读 IR JSON，逐 case 一个 GUT 测试方法
    （归因粒度 = case，失败测试名经 manifest 直接对回场景），按类型断言。

    harness 约定（被测项目侧须提供 res://addons/gqt_accept/harness.gd，
    遵循 testing_api 模板 init/execute/apply/query 连招）；生成脚本本身
    零业务逻辑，只有 IR 驱动循环——数字全部来自 IR。成功路径每 case 携带
    errs 空正断言（GUT 零断言测试判 [Risky]，hollow-green 防线）。

    /2 调用约定：run_step 全量 await 化——GDScript await 对非协程返回值
    透传（同步 harness 零破坏），场景生命周期步骤（settle_until 等）
    可为协程。整条调用链（GUT 测试方法 → _run_case_by_name → _run_case）
    相应协程化，GUT 9.x 原生支持 await 测试方法。
    """
    test_names = [c["test_name"] for c in ir["cases"]]
    methods = "\n\n".join(
        f'func {name}() -> void:\n'
        f'\tawait _run_case_by_name("{name}")'
        for name in test_names)
    return f"""# generated by gqt accept compile ({OPS_VERSION}) — DO NOT EDIT BY HAND
extends GutTest

const IR_PATH := "{ir_path_res}"
const OPS_VERSION := "{OPS_VERSION}"

var _cases_by_name := {{}}
var _harness: Object = null
var _baselines := {{}}

func before_all() -> void:
\tvar f := FileAccess.open(IR_PATH, FileAccess.READ)
\tassert_true(f != null, "IR file readable: " + IR_PATH)
\tif f == null:
\t\treturn
\tvar ir: Dictionary = JSON.parse_string(f.get_as_text())
\tassert_true(ir != null, "IR parses as JSON")
\tassert_true(String(ir.get("ops_version")) == OPS_VERSION,
\t\t"IR ops_version mismatch: " + String(ir.get("ops_version")))
\tfor case_v in ir.get("cases", []):
\t\t_cases_by_name[String(case_v.get("test_name", ""))] = case_v

func _make_harness() -> Object:
\tif not ResourceLoader.exists("res://addons/gqt_accept/harness.gd"):
\t\treturn null
\tvar script: GDScript = load("res://addons/gqt_accept/harness.gd")
\tvar h: Object = script.new()
\tif not h.smoke_check():
\t\treturn null
\treturn h

func _run_case_by_name(case_name: String) -> void:
\tif _harness == null:
\t\t_harness = _make_harness()
\tif _harness == null:
\t\tfail_test("accept harness unavailable (res://addons/gqt_accept/harness.gd missing or smoke_check failed)")
\t\treturn
\tvar case: Dictionary = _cases_by_name.get(case_name, {{}})
\tif case.is_empty():
\t\tfail_test("case missing from IR: " + case_name)
\t\treturn
\tvar errs: Array = await _run_case(_harness, case)
\tfor e in errs:
\t\tfail_test(String(e))
\t# 成功路径正断言（非装饰）：GUT 对零断言测试判 [Risky] did not assert，
\t# run 的 ok:true 将失去行为证据面（hollow-green）——每 case 必须真实
\t# 断言 errs 为空（附步骤数与 unchanged 槽数的逐 case 证据明细）。
\tassert_true(errs.is_empty(), "case '%s' verified: %d step(s) executed, %d unchanged slot(s) checked, %d error(s)" % [case_name, case.get("steps", []).size(), case.get("then_unchanged", []).size(), errs.size()])
\t_harness.reset()

{methods}

# 数据驱动执行：init → 基线快照（DEF-1 mutated_unchanged 基线污染探针）→
# steps → check_expectations → unchanged 比对。返回错误字符串数组。
func _run_case(harness: Object, case: Dictionary) -> Array:
\tvar errs: Array = []
\tvar err: String = harness.init_case(case)
\tif err != "":
\t\terrs.append("harness.init_case failed: " + err)
\t\treturn errs
\tvar mutated: Array = case.get("mutated_unchanged", [])
\tfor u in case.get("then_unchanged", []):
\t\tvar baseline = harness.query_state(String(u))
\t\tif mutated.has(String(u)):
\t\t\t# 防伪层③：标记串基线与真值必失配（比对块在位则必挂；被剥离
\t\t\t# 则探针失效 = survived）。GDScript 异类型 != 是报错面，走串形。
\t\t\tbaseline = "gqt-mutant-polluted"
\t\t_baselines[case.get("test_name", "?") + "|" + String(u)] = baseline
\tfor step_v in case.get("steps", []):
\t\tvar step: Dictionary = step_v
\t\t# /2 调用约定：await 透传——同步 harness 返回值原样穿透（零挂起），
\t\t# 协程形态（场景生命周期步骤）则挂起至完成。
\t\tvar step_err: String = await harness.run_step(step, case)
\t\tif step_err != "":
\t\t\terrs.append("step '%s %s' (line %s): %s" % [String(step.get("keyword", "")), String(step.get("text", "")), str(step.get("line", 0)), step_err])
\t\t\tbreak
\tif not errs.is_empty():
\t\treturn errs
\t# Then 期望值比对（数据驱动断言核心）：期望 cell 全在 case.values，
\t# 由 harness 按其 query 映射逐项核对——变异轮改的就是这些 cell。
\tvar assert_err: String = harness.check_expectations(case)
\tif assert_err != "":
\t\terrs.append("expectation check failed: " + assert_err)
\tfor u in case.get("then_unchanged", []):
\t\tvar key: String = case.get("test_name", "?") + "|" + String(u)
\t\t# str() 同形比较：对任意 query 返回类型恒合法且语义等价。
\t\tif str(harness.query_state(String(u))) != str(_baselines[key]):
\t\t\terrs.append("unchanged slot violated: %s" % String(u))
\treturn errs
"""


def _worker_gd_source() -> str:
    """常驻 worker 生成物（披露③，§SPEC-1426-14）：SceneTree 脚本，
    stdin NDJSON 循环消费变异 IR。

    QA-1 传输协议：`OS.read_string_from_stdin()` 有 1024 字节行缓冲上限
    （Revy 实机二分实证：1024B OK / 1025B FAIL），真实 IR 的带内 JSON 必
    挂死——请求行只携带小载荷 {mutant_id, ir_file}，变异 IR 本体经
    FileAccess 读请求指向的临时文件（零行缓冲限制）。

    每请求：加载 harness → 跑该 IR 全部 case（与生成测试同一语义）→
    回一行 NDJSON verdict；每 mutant 结束执行硬纪律——harness.reset() +
    释放实例（引用置空重建，reload 的 v1 落点）+ 自检探针（重建实例
    smoke_check 必须为真），不符即回 run_error verdict。

    /2 调用约定（SEE-1468 NDJSON 异步消费契约评审收口）：run_step await
    化后 _run_case 成为协程，而 `_init` 不可挂起——NDJSON 循环整体迁入
    fire-and-forget `_drive()` 协程：同步 harness 的 await 对非协程返回值
    透传、零挂起、控制流与 /1 逐字节等价；协程 harness（场景生命周期
    步骤）挂起时 SceneTree 主循环继续泵帧供其恢复。协议不变：请求行
    仍恒 <1024B，verdict 仍逐请求一行 JSON，读侧串行（CLI 一请求一
    verdict，无并发在途请求，无 stdin 异步消费竞争面）。

    首帧屏障（SEE-1468 F-D）：`-s` 裸 SceneTree 进程中 autoload 于首帧后
    才挂载，`_drive()` 在首个 await 前同步执行的 `_fresh_harness →
    smoke_check()` 会因依赖 autoload 的 harness 恒 false → 每 mutant
    run_error。`_drive()` 入口先 `await process_frame` 屏障一帧，autoload
    挂载完成后再进 harness 硬纪律校验；NDJSON 协议语义（串行读、超时
    封顶、行缓冲上限）零改动。
    """
    return f"""# generated by gqt accept compile ({OPS_VERSION}) — DO NOT EDIT BY HAND
extends SceneTree

const OPS_VERSION := "{OPS_VERSION}"

func _init() -> void:
\t# 协程化循环的落点：_init 内不可 await，_drive() 同步执行至首个
\t# await 点（首帧屏障）后让出，由主循环在信号/协程完成时恢复。
\t_drive()

func _drive() -> void:
\t# 首帧屏障（F-D）：-s 裸 SceneTree 进程中 autoload 于首帧后才挂载，
\t# 而 smoke_check 等就绪面校验依赖 autoload 就绪——屏障前做校验恒
\t# false → 每 mutant run_error。等首个 process_frame 后再进主循环。
\tawait process_frame
\tvar harness: Object = null
\twhile true:
\t\t# QA-1：请求行只带 {{"mutant_id", "ir_file"}} 小载荷（恒 <1024B），
\t\t# IR 本体走 ir_file 文件通道（FileAccess 无行缓冲上限）。
\t\tvar line := OS.read_string_from_stdin()
\t\tif line.strip_edges() == "":
\t\t\tbreak
\t\tvar req: Dictionary = JSON.parse_string(line)
\t\tif req == null or not req.has("ir_file"):
\t\t\tprint(JSON.stringify({{"run_error": "malformed worker request"}}))
\t\t\tcontinue
\t\tvar verdict: Dictionary = await _run_mutant(harness, req)
\t\tprint(JSON.stringify(verdict))
\tquit(0)

func _load_ir(req: Dictionary) -> Dictionary:
\tvar ir_path := String(req.get("ir_file", ""))
\tif ir_path.begins_with("res://"):
\t\tir_path = ProjectSettings.globalize_path(ir_path)
\tvar f := FileAccess.open(ir_path, FileAccess.READ)
\tif f == null:
\t\treturn {{}}
\tvar parsed = JSON.parse_string(f.get_as_text())
\tf.close()
\tif parsed == null or not parsed is Dictionary:
\t\treturn {{}}
\treturn parsed

func _fresh_harness(harness: Object) -> Object:
\t# 硬纪律释放面：旧实例引用全部置空后重建（drop = 释放全部
\t# testing_api 实例），重建即 reload 形态的 v1 落点。
\tharness = null
\tif not ResourceLoader.exists("res://addons/gqt_accept/harness.gd"):
\t\treturn null
\tvar script: GDScript = load("res://addons/gqt_accept/harness.gd")
\tvar h: Object = script.new()
\tif not h.smoke_check():
\t\treturn null
\treturn h

func _run_mutant(harness: Object, req: Dictionary) -> Dictionary:
\tvar mid := String(req.get("mutant_id", "?"))
\tvar ir: Dictionary = _load_ir(req)
\tif ir.is_empty():
\t\treturn {{"mutant_id": mid, "run_error": "ir_file unreadable or unparseable: " + String(req.get("ir_file", ""))}}
\tvar next_h := _fresh_harness(harness)
\tif next_h == null:
\t\treturn {{"mutant_id": mid, "run_error": "harness unavailable or smoke_check failed after instance release/rebuild"}}
\tharness = next_h
\tvar rc := 0
\tvar failing: Array = []
\tvar executed := 0
\tvar baselines := {{}}
\tfor case_v in ir.get("cases", []):
\t\tvar case: Dictionary = case_v
\t\tvar errs: Array = await _run_case(harness, case, baselines)
\t\texecuted += 1
\t\tif not errs.is_empty():
\t\t\trc = 1
\t\t\tfailing.append(String(case.get("test_name", "?")))
\t\tharness.reset()
\treturn {{"mutant_id": mid, "rc": rc, "executed": executed,
\t\t"failing": failing, "ops_version": String(ir.get("ops_version", ""))}}

# 与生成测试同一 case 语义：init → 基线快照（DEF-1 基线污染探针）→
# steps → check_expectations → unchanged 比对。
func _run_case(harness: Object, case: Dictionary, baselines: Dictionary) -> Array:
\tvar errs: Array = []
\tvar err: String = harness.init_case(case)
\tif err != "":
\t\terrs.append("harness.init_case failed: " + err)
\t\treturn errs
\tvar mutated: Array = case.get("mutated_unchanged", [])
\tfor u in case.get("then_unchanged", []):
\t\tvar baseline = harness.query_state(String(u))
\t\tif mutated.has(String(u)):
\t\t\t# 防伪层③：标记串基线与真值必失配（比对块在位则必挂；被剥离
\t\t\t# 则探针失效 = mutant survived = 打回）。
\t\t\tbaseline = "gqt-mutant-polluted"
\t\tbaselines[String(u)] = baseline
\tfor step_v in case.get("steps", []):
\t\tvar step: Dictionary = step_v
\t\t# /2 调用约定：await 透传（同生成测试侧注释——同步 harness 零挂起）。
\t\tvar step_err: String = await harness.run_step(step, case)
\t\tif step_err != "":
\t\t\terrs.append("step '%s %s' (line %s): %s" % [String(step.get("keyword", "")), String(step.get("text", "")), str(step.get("line", 0)), step_err])
\t\t\tbreak
\tif not errs.is_empty():
\t\treturn errs
\tvar assert_err: String = harness.check_expectations(case)
\tif assert_err != "":
\t\terrs.append("expectation check failed: " + assert_err)
\tfor u in case.get("then_unchanged", []):
\t\tif str(harness.query_state(String(u))) != str(baselines[String(u)]):
\t\t\terrs.append("unchanged slot violated: %s" % String(u))
\treturn errs
"""
def _build_manifest(ir: dict, ir_json: str, gd: str, worker_gd: str,
                    feature_key: str, source_path: str,
                    ir_rel: str) -> tuple[dict, str]:
    """scenario→test 归因 manifest + 哈希绑定（ir/generated/worker）。"""
    ir_hash = sha256_of(ir_json)
    generated_hash = sha256_of(gd)
    worker_hash = sha256_of(worker_gd)
    manifest = {
        "ops_version": OPS_VERSION,
        "feature": ir["feature"],
        "feature_key": feature_key,
        "source_path": source_path,
        "ir_path": f"res://{ir_rel}",
        "ir_hash": ir_hash,
        "generated_hash": generated_hash,
        "worker_hash": worker_hash,
        "worker_path": "res://" + f"{GENERATED_DIR}/accept_worker.gd",
        "bindings": {"ir": ir_hash, "generated": generated_hash,
                     "worker": worker_hash},
        "attribution": [
            {"test_name": c["test_name"], "scenario": c["scenario"],
             "scenario_line": c["scenario_line"],
             "example_row_line": c["example_row_line"]}
            for c in ir["cases"]
        ],
    }
    return manifest, json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True)


def _feature_key_conflict(root: Path, feature_key: str,
                          source: Path) -> dict | None:
    """§SPEC-1426-27：feature_key 冲突显式报错——不同 .feature 归一化成
    同一 key 时静默互相覆盖会掩盖生成物与源文件的对应关系。旧产物的
    相对 source_path 按项目根锚定（防调用方 CWD 漂移误报）。"""
    man_path = root / GENERATED_DIR / f"{feature_key}.manifest.json"
    if not man_path.is_file():
        return None
    try:
        existing = json.loads(man_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        # LOW-1：损坏 manifest 归统一 JSON 契约错误面（compile 裸抛会
        # 绕过 {ok:false + reason} 形态）——指示重编译而非裸 traceback。
        return {
            "reason": f"existing manifest for key {feature_key!r} is corrupt "
                      f"({type(e).__name__}: {e}) — recompile with "
                      f"gqt accept compile --write to regenerate"}
    if not isinstance(existing, dict):
        return {
            "reason": f"existing manifest for key {feature_key!r} is not a "
                      f"JSON object — recompile with "
                      f"gqt accept compile --write to regenerate"}
    prev = Path(existing.get("source_path", ""))
    if not prev.is_absolute():
        prev = root / prev
    if prev.resolve() != source.resolve():
        return {
            "reason": f"feature_key conflict: {feature_key!r} is already bound "
                      f"to source {existing.get('source_path')!r} — rename one of "
                      f"the .feature files (keys must be 1:1 with sources)"}
    return None


def compile_feature(feature_path: str | Path, project_root: str | Path,
                    *, write: bool = True,
                    clean: bool = True) -> tuple[CompiledSuite | None, dict]:
    """编译一个 .feature。write=False 时纯内存（golden-file 单测用）。

    Returns (suite, error) — error 非空 = parse 失败等 caller 错误。
    """
    # 源身份一律绝对化：manifest.source_path 与 key 冲突检测都以此比对
    # （相对路径会随调用方 CWD 漂移，造成同源误报冲突/异源漏报）。
    p = Path(feature_path).resolve()
    try:
        text = p.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as e:
        return None, {"reason": f"unreadable feature: {e}"}
    try:
        ir = build_ir(text, str(p))
    except GherkinSyntaxError as e:
        return None, {"reason": str(e)}

    feature_key = re.sub(r"[^A-Za-z0-9_]", "_", p.stem)
    ir_json = json.dumps(ir, ensure_ascii=False, indent=2, sort_keys=True)
    ir_rel = f"{IR_DIR}/{feature_key}.json"
    # GUT 目录扫描按文件名前缀过滤（默认 test_，本机 GUT 9.6 实测：非
    # test_ 前缀脚本直接被扫描忽略、Nothing was run）——生成文件名必须
    # 以 test_ 开头。
    gd_rel = f"{GENERATED_DIR}/test_{feature_key}.gd"
    gd = _generated_gd_source(ir, "res://" + ir_rel)
    # 常驻 worker 生成物（披露③）：落 GENERATED_DIR 受先清空再生成管辖；
    # 非 test_ 前缀 → GUT 目录扫描不收集，仅经 -s 显式拉起。
    worker_gd = _worker_gd_source()
    manifest, manifest_json = _build_manifest(ir, ir_json, gd, worker_gd,
                                              feature_key, str(p), ir_rel)
    suite = CompiledSuite(feature_key=feature_key, ir=ir, ir_json=ir_json,
                          generated_gd=gd, manifest=json.loads(manifest_json),
                          worker_gd=worker_gd)
    if not write:
        return suite, None

    root = Path(project_root)
    gut = root / "addons" / "gut" / "gut_cmdln.gd"
    if not gut.is_file():
        return None, {"reason": f"GUT runner not found: {gut}"}
    error = _feature_key_conflict(root, feature_key, p)
    if error is not None:
        return None, error
    # 先清空再生成（决策 §3.1a——一次性产物，防止陈旧生成物残留）。
    ir_dir = root / IR_DIR
    gen_dir = root / GENERATED_DIR
    if clean:
        for d in (ir_dir, gen_dir):
            if d.exists():
                shutil.rmtree(d)
    ir_dir.mkdir(parents=True, exist_ok=True)
    gen_dir.mkdir(parents=True, exist_ok=True)
    (root / ir_rel).write_text(ir_json, encoding="utf-8")
    gd_path = root / gd_rel
    gd_path.write_text(gd, encoding="utf-8")
    (root / GENERATED_DIR / "accept_worker.gd").write_text(worker_gd,
                                                           encoding="utf-8")
    man_path = root / GENERATED_DIR / f"{feature_key}.manifest.json"
    man_path.write_text(manifest_json, encoding="utf-8")
    return suite, None
