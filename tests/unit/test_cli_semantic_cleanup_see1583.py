# §SPEC-002 旧 CLI 单词守护（SEE-1583 Final Review 扩面；增量 hardener
# 收紧为 token 级判定）：src 内任何独立单词 accept / canonical 必须命中
# 以下合法类别——变更说明、机器身份/缓存目录、版本化标识、通道身份、
# 英文规范形术语；其余一律判红（旧命令名残留）。`acceptance` 因无词边界
# 不受本守护影响（域术语合法）。
# 豁免按「保留片段 span 覆盖该出现点」判定：同一行内保留 token 旁另出现
# 的裸旧词不再被整行允许逃逸（Revy LOW 闭合）。
OLD_CLI_WORD = re.compile(r"\b(accept|canonical)\b")
OLD_CLI_WORD_ALLOW_PARTS = (
    r"formerly `accept`",             # cli.py 变更说明（保留清单）
    r"原 accept",                     # 同左（中文注释）
    r"see1468-gherkin/2",              # IR ops 版本串
    r"gqt-accept-worker",             # 缓存目录（保留清单）
    r"gqt-canonical-prep",            # 缓存目录（保留清单）
    r"canonical-prep/2",              # 缓存 schema 版本串（保留清单）
    r"gqt-canonical-backups",         # per-uid 私有备份根（机器身份）
    r"canonical-union/",              # 版本化标识
    r"canonical-diagnostic/",         # 版本化标识
    r"canonical_recipe_hash",         # 机器面参数名
    r"canonical_union",               # 机器面值串
    r"canonical cold",                # coverlink 通道身份（保留清单）
    r"cold/canonical",                # 同上
    r"canonical: Given/When/Then",    # 英文规范形语义（parser 注释）
)
OLD_CLI_WORD_ALLOW = re.compile("|".join(OLD_CLI_WORD_ALLOW_PARTS))


def _old_cli_word_allowed(line: str, start: int, end: int) -> bool:
    return any(s.start() <= start and end <= s.end()
               for part in OLD_CLI_WORD_ALLOW_PARTS
               for s in re.finditer(part, line))


def _unallowed_old_cli_words(line: str) -> list[str]:
    return [m.group(0) for m in OLD_CLI_WORD.finditer(line)
            if not _old_cli_word_allowed(line, m.start(), m.end())]


class TestOldCliWordGuard:
    """SEE-1583 §SPEC-002 扩面：旧命令名单词在 src 全域的机器守护。"""

    def test_src_has_no_old_cli_words_outside_allowlist(self):
        bad = []
        for path, text in _py_texts(SRC):
            for lineno, line in enumerate(text.splitlines(), 1):
                for word in _unallowed_old_cli_words(line):
                    bad.append(f"{path.relative_to(SRC)}:{lineno} "
                               f"[{word}]: {line.strip()[:100]}")
        assert not bad, (
            "old CLI word (accept/canonical) outside allowlist:\n"
            + "\n".join(bad[:20]))

    def test_guard_replay_catches_old_copy(self):
        # 旧文案回放：修复前被点名/同类的表述必须全部判红（守护有效性
        # 自证；与现行树全绿构成双向判据）。
        samples = (
            '"""accept run：headless 执行生成套件',
            '"""accept mutate runner（SEE-1426 P3',
            'fail_test("accept harness unavailable ',
            "# 工具自产 recipe 不得被自家 canonical 拒绝",
            "# §SPEC-060f：canonical 实际产生、此前契约表缺失",
            '"""§SPEC-054 canonical 静态准备缓存',
            "先于 coverage/accept 的 GUT/重放等任何其他",
            "mutation/coverage/accept 的同等兜底在真实拉起点",
        )
        for sample in samples:
            assert OLD_CLI_WORD.search(sample), sample
            assert not OLD_CLI_WORD_ALLOW.search(sample), sample


class TestOldInvocationFormGuard:
    """SEE-1583 §SPEC-002：src 内不得出现旧一级调用形态（四种形态）。

    判据形态为 `gqt <old-top-level>`（accept/arch/attr-update/canonical/
    canonical-diagnose/complexity/coverage/parity/recipe/registry/risk），
    并覆盖 Revy 登记的四类逃逸向量：多空白/Tab 分隔、`$GQT <old>` 变量
    形态、`python3 -m godot_qa_toolkit.cli <old>` 模块形态、名称大小写
    变体。新命令路径 `gqt measure <leaf>` / `gqt mutation` /
    `gqt gherkin …` 及其模块/变量形态不含 `gqt <old>` 前缀，不会误伤。
    """

    def test_src_has_no_old_invocation_forms(self):
        bad = []
        for path, text in _py_texts(SRC):
            for lineno, line in enumerate(text.splitlines(), 1):
                if OLD_INVOCATION.search(line):
                    bad.append(f"{path.relative_to(SRC)}:{lineno}: "
                               f"{line.strip()[:100]}")
        assert not bad, (
            "old top-level invocation form (gqt/$GQT/python -m cli <old>) "
            "in src:\n" + "\n".join(bad[:20]))

    def test_guard_replay_catches_old_invocations(self):
        # 旧串回放（含 LOW-1 修复前原文与四类逃逸形态）：必须判红。
        old_samples = (
            'push_error("gqt coverage probe sink open failed: user://" '
            "+ sink_name)",
            "raise RuntimeError('gqt complexity gate failed')",
            "log('gqt canonical report written')",
            "cmd = 'gqt accept compile foo.feature'",
            "# probe: $GQT coverage check",
            "# probe: python3 -m godot_qa_toolkit.cli recipe d.json",
            "# probe: gqt   complexity src/",
            "# probe: gqt Canonical report written",
        )
        for sample in old_samples:
            assert OLD_INVOCATION.search(sample), sample
        # 新命令路径与保留形态不得误伤（含对应变量/模块形态与近形）。
        for sample in (
            'push_error("gqt measure coverage probe sink open failed: '
            'user://" + sink_name)',
            "gqt measure complexity src/",
            "gqt mutation file.gd",
            "gqt gherkin compile foo.feature",
            "gqt doctor",
            "# probe: $GQT measure coverage check",
            "# probe: python3 -m godot_qa_toolkit.cli measure run "
            "--project-root p",
            "# probe: gqt   mutation file.gd",
            "# probe: gqt Canonicalize src/",
        ):
            assert not OLD_INVOCATION.search(sample), sample
