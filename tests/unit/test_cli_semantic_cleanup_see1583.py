"""SEE-1583 §SPEC-002 — 内部语义与命名清理判据。

判据面：
- 模块面：`accept/` → `gherkin/`、`canonical/` → `measurement/`，旧目录不存在；
- handler / argparse dest：无 cmd_gherkin/cmd_canonical 等旧 handler，新 handler
  齐备；gherkin_command / measure_command dest 生效；
- machine 面：src 内所有 stdout `tool` 字面值 ∈ 新命名集合；三个版本化标识
  `measurement-suite/2` / `measurement-report/2` / `test-attribution/5` 生效，
  旧 schema 串零残留（无双读）；
- 旧语义文案：SEE-1581 定稿后，mutation 侧不得再写「自动回退全脸」类
  help/docstring（fail-loud + 文件级有界回退是现行语义）；
- 生成产物头：`generated by gqt gherkin compile`，旧 `gqt accept compile` 零残留。
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "src" / "godot_qa_toolkit"

ALLOWED_TOOLS = {
    "gherkin", "mutation",
    "measure.suite", "measure.run", "measure.diagnose", "measure.map-update",
    "measure.coverage", "measure.complexity", "measure.arch", "measure.parity",
    "measure.registry-diff", "measure.risk",
}

TOOL_LITERAL = re.compile(r'"tool":\s*"([^"]+)"')

OLD_TOOL_LITERALS = ("accept", "arch", "canonical", "canonical-diagnose",
                     "complexity", "coverage", "parity", "recipe", "registry",
                     "risk")

OLD_SCHEMA_PREFIXES = ("canonical-recipe/", "canonical-report/",
                       "canonical-test-attribution/")

# mutation 侧旧「自动回退全脸」文案特征（现行语义：fail-loud / 有界文件级
# 回退 / zero-ref 终态 / 全脸仅显式审计）。measurement/increment 的「回退全脸」
# 是映射重建的校准策略，不属此判据，故仅扫 mutation/。
STALE_FULL_FACE = re.compile(r"退回全脸|走全脸|回退全脸|全脸回退|"
                             r"falls back to the full face|"
                             r"falls back to full suite")


def _py_texts(root: Path) -> list[tuple[Path, str]]:
    return [(p, p.read_text(encoding="utf-8")) for p in sorted(root.rglob("*.py"))]


class TestModuleNaming:
    def test_new_module_dirs_exist(self):
        assert (SRC / "gherkin").is_dir()
        assert (SRC / "measurement").is_dir()

    def test_old_module_dirs_gone(self):
        assert not (SRC / "accept").exists()
        assert not (SRC / "canonical").exists()


class TestHandlerAndDest:
    def test_old_handlers_gone(self):
        from godot_qa_toolkit import cli

        for gone in ("cmd_accept", "cmd_canonical", "cmd_canonical_diagnose",
                     "cmd_attr_update", "cmd_recipe", "cmd_registry",
                     "_accept_compile"):
            assert not hasattr(cli, gone), f"stale handler {gone} still present"

    def test_new_handlers_present(self):
        from godot_qa_toolkit import cli

        for want in ("cmd_gherkin", "cmd_measure_run", "cmd_measure_diagnose",
                     "cmd_measure_map_update", "cmd_measure_suite",
                     "cmd_measure_registry_diff", "cmd_measure_arch",
                     "cmd_measure_complexity", "cmd_measure_coverage",
                     "cmd_measure_parity", "cmd_measure_risk"):
            assert callable(getattr(cli, want, None)), \
                f"missing handler {want}"

    def test_group_dests_follow_new_semantics(self):
        from godot_qa_toolkit.cli import build_parser

        parser = build_parser()
        command = next(a for a in parser._actions
                       if getattr(a, "dest", "") == "command")
        by_dest = {}
        for group_name in ("gherkin", "measure"):
            group = command.choices[group_name]
            for action in group._actions:
                if isinstance(getattr(action, "choices", None), dict):
                    by_dest[action.dest] = set(action.choices)
        assert by_dest.get("gherkin_command") == {"compile", "run", "mutate"}
        assert by_dest.get("measure_command") == {
            "suite", "run", "diagnose", "map-update", "coverage", "complexity",
            "arch", "parity", "registry-diff", "risk"}
        assert "accept_command" not in by_dest
        assert "registry_command" not in by_dest


class TestMachineContract:
    def test_all_src_tool_literals_use_new_paths(self):
        values = {}
        for path, text in _py_texts(SRC):
            for match in TOOL_LITERAL.finditer(text):
                values.setdefault(match.group(1), []).append(
                    f"{path.relative_to(SRC)}:{text[:match.start()].count(chr(10)) + 1}")
        assert set(values) == ALLOWED_TOOLS, (
            f"unexpected tool literals: "
            f"{ {k: v[:2] for k, v in values.items() if k not in ALLOWED_TOOLS} }"
        )

    def test_no_old_tool_name_literals(self):
        # 逐个旧名显式断言：即便上面集合判据给出全量差集，这里保证每个旧
        # 名的消失都有具名反例（QA 对抗面）。
        for path, text in _py_texts(SRC):
            for old in OLD_TOOL_LITERALS:
                hits = [m.start() for m in
                        re.finditer(rf'"tool":\s*"{old}"', text)]
                assert not hits, (
                    f"{path.relative_to(SRC)} still emits tool {old!r}")

    def test_no_old_schema_versions_in_src(self):
        for path, text in _py_texts(SRC):
            for prefix in OLD_SCHEMA_PREFIXES:
                assert prefix not in text, (
                    f"{path.relative_to(SRC)} still references {prefix}"
                    " (dual-read forbidden)")

    def test_versioned_identifiers_active(self):
        from godot_qa_toolkit.measurement.orchestrator import (
            ATTRIBUTION_SCHEMA,
            REPORT_VERSION,
        )
        from godot_qa_toolkit.measurement.recipe import RECIPE_VERSION
        from godot_qa_toolkit.mutation.truth_select import SCHEMA_VERSION

        assert RECIPE_VERSION == "measurement-suite/2"
        assert REPORT_VERSION == "measurement-report/2"
        assert ATTRIBUTION_SCHEMA == "test-attribution/5"
        assert SCHEMA_VERSION == "test-attribution/5"


class TestStaleTextCleanup:
    def test_no_stale_full_face_fallback_text_in_mutation(self):
        for path, text in _py_texts(SRC / "mutation"):
            match = STALE_FULL_FACE.search(text)
            assert match is None, (
                f"{path.relative_to(SRC)} keeps stale auto-full-face text: "
                f"{text[max(0, match.start() - 40):match.end() + 40]!r}"
            )

    def test_cli_help_no_stale_fallback_claims(self):
        cli_text = (SRC / "cli.py").read_text(encoding="utf-8")
        # SEE-1581 定稿：--tests 零引用是终态短路、映射不可用 fail-loud，
        # help 不得再宣称回退全 suite / 全脸。
        assert "falls back to full suite" not in cli_text
        assert "falls back to the full face" not in cli_text


class TestGeneratedHeaders:
    def test_gherkin_generated_header_uses_new_command(self):
        text = (SRC / "gherkin" / "compile.py").read_text(encoding="utf-8")
        assert "generated by gqt gherkin compile" in text

    def test_no_old_generated_header_in_src(self):
        for path, text in _py_texts(SRC):
            assert "gqt accept compile" not in text, (
                f"{path.relative_to(SRC)} still tells users to run "
                "`gqt accept compile`")
